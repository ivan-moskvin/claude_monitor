const (
	glyphWidth  = 5
	glyphHeight = 7
)

// textWidth — ширина строки в пикселях при заданном масштабе, с пробелом в
// один пиксель между глифами.
func textWidth(text string, scale int) int {
	runes := []rune(text)
	if len(runes) == 0 {
		return 0
	}
	return len(runes)*(glyphWidth*scale+scale) - scale
}

// drawText рисует строку от левого верхнего угла (x, y) цветом idx.
func (p *panel) drawText(text string, x, y, scale int, idx uint8) {
	p.drawTextSplit(text, x, y, scale, panelSize, idx, idx)
}

// drawTextSplit красит текст двумя цветами: левее splitX одним, правее другим.
// Так подпись остаётся читаемой, когда полоса заполнена наполовину и буква
// стоит ровно на границе залитой и пустой части.
func (p *panel) drawTextSplit(text string, x, y, scale, splitX int, left, right uint8) {
	cursor := x
	for _, r := range text {
		glyph, ok := glyphs[r]
		if !ok {
			glyph = glyphs['?']
		}
		for row := 0; row < glyphHeight; row++ {
			for col := 0; col < glyphWidth; col++ {
				if glyph[row][col] != '1' {
					continue
				}
				px := cursor + col*scale
				idx := right
				if px < splitX {
					idx = left
				}
				p.fillRect(px, y+row*scale, scale, scale, idx)
			}
		}
		cursor += glyphWidth*scale + scale
	}
}

// drawTextCentered центрирует строку по горизонтали относительно всей панели.
func (p *panel) drawTextCentered(text string, y, scale int, idx uint8) {
	p.drawText(text, (panelSize-textWidth(text, scale))/2, y, scale, idx)
}
